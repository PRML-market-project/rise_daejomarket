export function createTranslator(language: Language, translations: Translations = {}) {
  return (source: string, params: Record<string, string | number> = {}) => {
    const key = source.trim();
    const text = language === "ko" ? source : copy[key]?.[language === "en" ? 0 : 1]
      ?? translations[key]?.[language] ?? source;
    return text.replace(/\{(\w+)\}/g, (match, key: string) => String(params[key] ?? match));
  };
}

export const KioskLocaleContext = createContext({ language: "ko" as Language, t: createTranslator("ko") });
export const useKioskLocale = () => useContext(KioskLocaleContext);
